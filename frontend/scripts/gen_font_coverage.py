"""
Generate `frontend/src/lib/fontCoverage.ts` from the BACKEND's own rules.

    backend\\.venv\\Scripts\\python.exe frontend\\scripts\\gen_font_coverage.py

The browser has to refuse a character before finalize does, and the only way
the two can never disagree is to ask the code the server runs:

* standard-14 families (Helvetica / Times-Roman / Courier): a character is
  drawable when reportlab's `unicode2T1` keeps it in the font asked for
  (`app.services.pdf_builder.undrawable_character`);
* embedded faces (Liberation; editor v2 B2: + Arimo, Carlito, Caladea,
  DejaVu Sans/Serif, Amiri): the TrueType cmap, minus what
  `app.services.fonts.embedded_refusal` refuses (control/format/private-use,
  combining marks, right-to-left).

The output is a list of inclusive [start, end] code-point ranges per face.
Re-run it whenever the font files or those two functions change.
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
BACKEND = os.environ.get("SWM_BACKEND_DIR") or os.path.join(ROOT, "backend")
if not os.path.isdir(os.path.join(BACKEND, "app")):
    # The staging copy has no backend of its own: use the live one, read-only.
    BACKEND = r"C:\PTG\signwithme\backend"
sys.path.insert(0, BACKEND)

from reportlab.pdfbase import pdfmetrics  # noqa: E402

from app.services.fonts import (  # noqa: E402
    BASE14_FAMILIES,
    EMBEDDED_FAMILIES,
    embedded_refusal,
    glyph_map,
)

OUT = os.path.join(HERE, "..", "src", "lib", "fontCoverage.ts")


def ranges(points: list[int]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in sorted(points):
        if out and cp == out[-1][1] + 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def base14_points(face_name: str) -> list[int]:
    face = pdfmetrics.getFont(face_name)
    keep: list[int] = []
    for cp in range(0x20, 0x10000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        char = chr(cp)
        if all(used is face for used, _ in pdfmetrics.unicode2T1(char, [face])):
            keep.append(cp)
    return keep


def embedded_points(face_name: str) -> list[int]:
    cmap = glyph_map(face_name)
    return [cp for cp in cmap if embedded_refusal(chr(cp), cmap) is None]


def main() -> None:
    faces: dict[str, list[tuple[int, int]]] = {}
    base = None
    for family, names in BASE14_FAMILIES.items():
        for name in names:
            got = ranges(base14_points(name))
            if base is None:
                base = got
            elif got != base:
                raise SystemExit(f"{name}: WinAnsi coverage differs from Helvetica -- update the generator")
    for family, names in EMBEDDED_FAMILIES.items():
        for name in names:
            faces[name] = ranges(embedded_points(name))

    def fmt(rs: list[tuple[int, int]]) -> str:
        return "[" + ",".join(f"[{a},{b}]" for a, b in rs) + "]"

    lines = [
        "/* eslint-disable */",
        "// GENERATED by frontend/scripts/gen_font_coverage.py -- do not edit by hand.",
        "// Source: the backend's own checks (reportlab `unicode2T1` for the standard 14,",
        "// every embedded TrueType cmap minus `fonts.embedded_refusal` for the embedded",
        "// faces). Inclusive code-point ranges, sorted.",
        "",
        "/** What every standard-14 face (Helvetica / Times / Courier, any style) can print: WinAnsi. */",
        f"export const WINANSI_RANGES: ReadonlyArray<readonly [number, number]> = {fmt(base or [])};",
        "",
        "/** Per embedded face (`LiberationSans`, `LiberationSans-Bold`, ...): what it can print. */",
        "export const EMBEDDED_RANGES: Readonly<Record<string, ReadonlyArray<readonly [number, number]>>> = {",
    ]
    for name, rs in faces.items():
        lines.append(f"  '{name}': {fmt(rs)},")
    lines.append("};")
    lines.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, ROOT)}: WinAnsi {len(base or [])} ranges, "
          + ", ".join(f"{k} {len(v)}" for k, v in faces.items()))


if __name__ == "__main__":
    main()
