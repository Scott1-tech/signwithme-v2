"""Artefact storage: original uploads, templates, signature images, final PDFs.

Two backends, chosen by STORAGE_BACKEND:

* ``s3`` -- MinIO or Amazon S3, for deployments with room to run it.
* ``local`` -- a plain directory on a mounted volume. MinIO idles at a few
  hundred megabytes, which is a quarter of a 1 GB machine; on small hosts the
  filesystem is the better object store.

Both expose the same interface, so nothing above this module knows which is in
use. Files are always served *through* the API, never by a direct link to the
storage layer: these documents contain SSNs, so every read passes the same
authorisation check.
"""
from __future__ import annotations

import io
import logging
import os
import re
import tempfile
from contextlib import contextmanager
from pathlib import Path

import boto3
from botocore.client import Config
from botocore.exceptions import BotoCoreError, ClientError

from app.config import settings
from app.core.exceptions import StorageError

logger = logging.getLogger(__name__)

# Same anchor `local_run.py:21` uses: the directory the backend package lives in.
# storage.py is backend/app/services/storage.py, so parents[2] is backend/.
BACKEND_DIR = Path(__file__).resolve().parents[2]

# Windows extended-length path prefixes. `_getfinalpathname` -- the syscall
# behind `os.path.realpath` and `Path.resolve` -- always answers with one of
# these, and `ntpath.realpath` removes it again only under the condition
# described on `LocalStorage._path`. Whatever survives that, both sides of a
# containment check have to be spelled the same way.
_EXTENDED_PREFIX = "\\\\?\\"
_EXTENDED_UNC_PREFIX = "\\\\?\\UNC\\"

# A key that begins with a drive letter is drive-qualified even without a
# separator: "C:evil.png" means "evil.png on C:'s current directory".
_DRIVE_LETTER = re.compile(r"^[A-Za-z]:")

# `/` and `\` both, on every platform. A key is generated by this module, so
# neither ever appears as anything but a separator, and refusing one on POSIX
# costs nothing while keeping the rule identical on both.
_SEPARATORS = re.compile(r"[\\/]")

PREFIX_TEMPLATES = "templates"
PREFIX_CONTRACTS = "contracts"
PREFIX_SIGNATURES = "signatures"
PREFIX_USER_SIGNATURES = "user-signatures"
PREFIX_FINAL = "final"

# `delete_prefix` removes one object's folder and nothing wider: exactly
# "<known prefix>/<one id segment>". A bare "contracts" (or "") must never
# reach a recursive delete, whatever a caller computes.
_SCOPED_PREFIX = re.compile(
    r"^(templates|contracts|signatures|user-signatures|final)/[A-Za-z0-9-]+$"
)


def _require_scoped_prefix(prefix: str) -> None:
    if not isinstance(prefix, str) or not _SCOPED_PREFIX.match(prefix):
        raise StorageError(f"Refusing to delete an unscoped storage prefix: {prefix!r}")


class S3Storage:
    def __init__(self):
        self._client = None

    @property
    def client(self):
        if self._client is None:
            self._client = boto3.client(
                "s3",
                endpoint_url=settings.s3_endpoint_url,
                aws_access_key_id=settings.minio_access_key,
                aws_secret_access_key=settings.minio_secret_key,
                config=Config(signature_version="s3v4"),
                region_name="us-east-1",
            )
        return self._client

    def ensure_bucket(self) -> None:
        try:
            self.client.head_bucket(Bucket=settings.minio_bucket)
        except ClientError:
            try:
                self.client.create_bucket(Bucket=settings.minio_bucket)
            except (ClientError, BotoCoreError) as exc:
                raise StorageError(f"Could not create bucket: {exc}") from exc

    def put_bytes(self, key: str, data: bytes, content_type: str = "application/pdf") -> str:
        try:
            self.client.put_object(
                Bucket=settings.minio_bucket, Key=key, Body=data, ContentType=content_type
            )
        except (ClientError, BotoCoreError) as exc:
            raise StorageError(f"Upload failed for {key}: {exc}") from exc
        return key

    def put_file(self, key: str, path: str, content_type: str = "application/pdf") -> str:
        with open(path, "rb") as handle:
            return self.put_bytes(key, handle.read(), content_type)

    def get_bytes(self, key: str) -> bytes:
        try:
            response = self.client.get_object(Bucket=settings.minio_bucket, Key=key)
            return response["Body"].read()
        except (ClientError, BotoCoreError) as exc:
            raise StorageError(f"Download failed for {key}: {exc}") from exc

    def stream(self, key: str) -> io.BytesIO:
        return io.BytesIO(self.get_bytes(key))

    def presigned_url(self, key: str, filename: str | None = None, ttl: int | None = None) -> str:
        params = {"Bucket": settings.minio_bucket, "Key": key}
        if filename:
            params["ResponseContentDisposition"] = f'attachment; filename="{filename}"'
        try:
            return self.client.generate_presigned_url(
                "get_object",
                Params=params,
                ExpiresIn=ttl or settings.presigned_url_ttl_seconds,
            )
        except (ClientError, BotoCoreError) as exc:
            raise StorageError(f"Could not sign URL for {key}: {exc}") from exc

    def delete(self, key: str) -> None:
        try:
            self.client.delete_object(Bucket=settings.minio_bucket, Key=key)
        except (ClientError, BotoCoreError) as exc:
            logger.warning("Failed to delete %s: %s", key, exc)

    def delete_prefix(self, prefix: str) -> None:
        """Best-effort removal of every object under ``<prefix>/`` (one id folder)."""
        _require_scoped_prefix(prefix)
        try:
            paginator = self.client.get_paginator("list_objects_v2")
            for page in paginator.paginate(Bucket=settings.minio_bucket, Prefix=prefix + "/"):
                for item in page.get("Contents", []):
                    self.delete(item["Key"])
        except (ClientError, BotoCoreError) as exc:
            logger.warning("Failed to delete prefix %s: %s", prefix, exc)

    @contextmanager
    def local_copy(self, key: str, suffix: str = ".pdf"):
        """Materialise an object on local disk; pdfplumber and pypdf want a path."""
        handle = tempfile.NamedTemporaryFile(suffix=suffix, delete=False)
        try:
            handle.write(self.get_bytes(key))
            handle.flush()
            handle.close()
            yield handle.name
        finally:
            try:
                os.unlink(handle.name)
            except OSError:
                pass


def _resolve_root(raw: str) -> Path:
    """Turn a configured storage_dir into one absolute path, for every CWD.

    A relative `storage_dir` used to be resolved against the process working
    directory, so the same configuration pointed at different directories
    depending on how the API was started (`local_run.py` pins the CWD, a bare
    `uvicorn app.main:app`, a Celery worker or a service wrapper does not).
    Keys written by one process then read as "outside the storage root" in
    another. Relative values are anchored to `backend/` instead; absolute ones
    are used exactly as given.

    Note for Windows: a rooted path with no drive ("/data/storage", the POSIX
    default) is *not* absolute there -- it inherits the drive of the CWD. Such
    a value counts as relative here and is anchored too; on Linux, where the
    Docker image runs, it is absolute and untouched.
    """
    path = Path(raw)
    if not path.is_absolute():
        path = BACKEND_DIR / path
    return _strip_extended_prefix(path.resolve())


def _strip_extended_prefix(path: Path) -> Path:
    r"""Drop a Windows `\\?\` (or `\\?\UNC\`) prefix; leave anything else alone.

    `Path.resolve()` returns the prefixed spelling unpredictably (see
    `LocalStorage._path`), and `\\?\C:\x` and `C:\x` name the same file but do
    not compare equal. Normalising both sides through here makes the
    difference invisible instead of fatal.
    """
    text = str(path)
    if text.startswith(_EXTENDED_UNC_PREFIX):
        return Path("\\\\" + text[len(_EXTENDED_UNC_PREFIX) :])
    if text.startswith(_EXTENDED_PREFIX):
        return Path(text[len(_EXTENDED_PREFIX) :])
    return path


def _reject_unsafe_key(key: str) -> None:
    """Refuse anything that is not a plain relative key, before any path maths.

    Every one of these would, once joined, be interpreted differently by
    `os.path.join` on Windows and on POSIX -- an absolute or drive-qualified
    component silently *replaces* the root it is joined to. Refusing them up
    front means the join below cannot produce a surprise on either platform.
    """
    if not isinstance(key, str) or not key:
        raise StorageError("Refusing an empty storage key")
    if "\x00" in key:
        raise StorageError("Refusing a storage key containing a null byte")
    if key.startswith("\\\\") or key.startswith("//"):
        raise StorageError(f"Refusing to access a key outside the storage root: {key}")
    if _DRIVE_LETTER.match(key) or os.path.isabs(key):
        raise StorageError(f"Refusing to access a key outside the storage root: {key}")
    if ".." in _SEPARATORS.split(key):
        raise StorageError(f"Refusing to access a key outside the storage root: {key}")


class LocalStorage:
    """Filesystem-backed store with the same interface as S3Storage.

    Keys are treated as relative paths under `storage_dir`; each is checked to
    stay inside that root, so a crafted key cannot escape via `..`.
    """

    def __init__(self, root: str | None = None):
        # Resolved once, at construction: the root must not move underneath a
        # running process, and both sides of the containment check below have
        # to be normalised the same way.
        self.root = _resolve_root(root or settings.storage_dir)

    def _path(self, key: str) -> Path:
        r"""Map a key onto a path inside the root, deciding containment *lexically*.

        The obvious spelling -- resolve the joined path and ask whether it sits
        under the resolved root -- is wrong on Windows, because `Path.resolve()`
        is not a pure function of its argument. `ntpath.realpath`
        (CPython 3.12 `Lib/ntpath.py:726-765`) asks the OS to canonicalise the
        path, always gets back a `\\?\`-prefixed answer, and strips that prefix
        again only if a *second* probe of the stripped spelling either succeeds
        or fails with exactly the same winerror as the first.

        Two requests writing signatures for one contract race there. The first
        probe fails with ERROR_PATH_NOT_FOUND (3) because `signatures/<id>/`
        does not exist yet; the other request's `mkdir(parents=True)` then
        creates it; the second probe now fails with ERROR_FILE_NOT_FOUND (2).
        3 != 2, so the prefix stays, and `\\?\...\storage\signatures\x.png` is
        not `is_relative_to` a root that was resolved back when the directory
        did exist. The result was a ~5% "outside the storage root" rate on
        parallel uploads -- a false positive, never an attack, and invisible to
        a retry because by then the directory exists for both probes.

        So containment is decided on text alone, touching no filesystem state.
        Nothing is lost by that: keys are built here out of UUIDs
        (`signature_key` and friends), never out of caller-supplied text, so
        there is no spelling to canonicalise away. `_reject_unsafe_key` has
        already refused every component that `os.path.join` would treat as a
        new root, and `normpath` collapses separators without consulting disk.
        """
        _reject_unsafe_key(key)
        candidate = Path(os.path.normpath(os.path.join(str(self.root), key)))
        # Belt and braces behind the `..` refusal above. Compared on path
        # components, not on the string prefix: "../storage-evil/x.png" names a
        # *sibling* directory whose name starts with the root's, which a
        # str.startswith() test lets through.
        if not candidate.is_relative_to(self.root):
            raise StorageError(f"Refusing to access a key outside the storage root: {key}")
        self._reject_link_out_of_root(candidate, key)
        return candidate

    def _reject_link_out_of_root(self, candidate: Path, key: str) -> None:
        r"""Defence in depth: refuse an existing entry that a link moves out of the root.

        A lexical check cannot see a symlink or an NTFS junction planted inside
        the root. Nothing reachable over the API can plant one -- every key
        component is a server-generated UUID, and no endpoint creates a
        directory entry under a caller-chosen name -- so an attacker would need
        filesystem write access as this user first, at which point the guard is
        moot anyway. This is therefore a second line, not the first.

        It is built so it cannot produce a false positive, which is the whole
        point of the change above: it runs only when the entry already exists,
        it canonicalises *both* sides the same way (including the `\\?\` prefix
        that started all this), and any OS error means "no opinion" rather than
        "refuse".
        """
        try:
            if not os.path.lexists(candidate):
                return
            real = _strip_extended_prefix(Path(os.path.realpath(candidate)))
            real_root = _strip_extended_prefix(Path(os.path.realpath(self.root)))
        except (OSError, ValueError):
            return
        if not real.is_relative_to(real_root):
            raise StorageError(f"Refusing to access a key outside the storage root: {key}")

    def ensure_bucket(self) -> None:
        try:
            self.root.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise StorageError(f"Could not create the storage directory: {exc}") from exc

    def put_bytes(self, key: str, data: bytes, content_type: str = "application/pdf") -> str:
        path = self._path(key)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Write then rename: a crash mid-write must not leave a truncated
            # contract behind a valid-looking key.
            temporary = path.with_suffix(path.suffix + ".partial")
            temporary.write_bytes(data)
            temporary.replace(path)
        except OSError as exc:
            raise StorageError(f"Upload failed for {key}: {exc}") from exc
        return key

    def put_file(self, key: str, path: str, content_type: str = "application/pdf") -> str:
        with open(path, "rb") as handle:
            return self.put_bytes(key, handle.read(), content_type)

    def get_bytes(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except OSError as exc:
            raise StorageError(f"Download failed for {key}: {exc}") from exc

    def stream(self, key: str) -> io.BytesIO:
        return io.BytesIO(self.get_bytes(key))

    def presigned_url(self, key: str, filename: str | None = None, ttl: int | None = None) -> str:
        raise StorageError(
            "The local backend has no presigned URLs; files are served through the API."
        )

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink(missing_ok=True)
        except OSError as exc:
            logger.warning("Failed to delete %s: %s", key, exc)

    def delete_prefix(self, prefix: str) -> None:
        """Best-effort removal of one id folder: its regular files, then the folder.

        Every file goes through ``delete`` and so through ``_path``; the folder
        itself too. Links are never followed: a symlink or junction in place of
        the folder is left alone, as is any entry that is not a regular file
        (the final ``rmdir`` then fails, which is logged, not raised).
        """
        _require_scoped_prefix(prefix)
        directory = self._path(prefix)
        try:
            if directory.is_symlink() or directory.is_junction() or not directory.is_dir():
                return
            with os.scandir(directory) as entries:
                names = [entry.name for entry in entries if entry.is_file(follow_symlinks=False)]
            for name in names:
                self.delete(f"{prefix}/{name}")
            directory.rmdir()
        except OSError as exc:
            logger.warning("Failed to delete prefix %s: %s", prefix, exc)

    @contextmanager
    def local_copy(self, key: str, suffix: str = ".pdf"):
        # Already on disk; pdfplumber can open it in place.
        yield str(self._path(key))


def _build_storage():
    if settings.storage_backend == "local":
        return LocalStorage()
    return S3Storage()


storage = _build_storage()


def template_key(template_id, filename: str = "source.pdf") -> str:
    return f"{PREFIX_TEMPLATES}/{template_id}/{filename}"


def contract_key(contract_id, filename: str = "original.pdf") -> str:
    return f"{PREFIX_CONTRACTS}/{contract_id}/{filename}"


def signature_key(contract_id, signature_id) -> str:
    return f"{PREFIX_SIGNATURES}/{contract_id}/{signature_id}.png"


def user_signature_key(user_id, signature_id) -> str:
    """Storage key for a user's private, reusable signature PNG.

    Keyed by owner id so one user's library never shares a path prefix with
    another's; the bytes are still served only through the authenticated,
    ownership-checked API endpoint.
    """
    return f"{PREFIX_USER_SIGNATURES}/{user_id}/{signature_id}.png"


_ASSET_ID = re.compile(r"^[0-9a-f]{32}$")


def annotation_asset_key(contract_id, asset_id: str) -> str:
    """Storage key of an annotation `image` asset (contract v5).

    Flat inside the CONTRACT's own folder -- `contracts/<id>/asset-<hex>.png`,
    no sub-folder -- so the admin contract deletion's
    `delete_prefix("contracts/<id>")` (which removes the regular files of that
    one folder) takes every asset with it. The contract id in the key is what
    makes an asset id from another contract simply not exist here (no IDOR).
    `asset_id` is server-generated (uuid4().hex); anything else is refused
    before it gets near a path.
    """
    if not isinstance(asset_id, str) or not _ASSET_ID.match(asset_id):
        raise StorageError("Refusing a malformed annotation asset id")
    return f"{PREFIX_CONTRACTS}/{contract_id}/asset-{asset_id}.png"


PREFIX_USER_ASSETS = "user-assets"


def user_asset_key(user_id, asset_id: str) -> str:
    """A user's gallery image (editor v2 B2): `user-assets/<user>/<hex>.png`.
    Served only through the owner-checked `/api/assets/{id}/image`."""
    if not isinstance(asset_id, str) or not _ASSET_ID.match(asset_id):
        raise StorageError("Refusing a malformed asset id")
    return f"{PREFIX_USER_ASSETS}/{user_id}/{asset_id}.png"


def export_key(contract_id, job_id: str) -> str:
    """An export result: flat in the contract's folder (taken by the admin
    deletion's `delete_prefix`)."""
    if not isinstance(job_id, str) or not _ASSET_ID.match(job_id):
        raise StorageError("Refusing a malformed export id")
    return f"{PREFIX_CONTRACTS}/{contract_id}/export-{job_id}.pdf"


def final_key(contract_id) -> str:
    return f"{PREFIX_FINAL}/{contract_id}/signed.pdf"
